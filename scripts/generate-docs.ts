// ---------- QA report ----------
interface PwSpec {
  title: string;
  ok: boolean;
  tests: { results: { status: string; duration: number }[] }[];
}
interface PwSuite {
  title: string;
  specs?: PwSpec[];
  suites?: PwSuite[];
}
const flatten = (s: PwSuite): PwSpec[] => [...(s.specs ?? []), ...(s.suites ?? []).flatMap(flatten)];
const pwPath = resolve(ROOT, 'test-results/results.json');
const pw = existsSync(pwPath)
  ? (JSON.parse(readFileSync(pwPath, 'utf8')) as { suites: PwSuite[]; stats: { expected: number; unexpected: number; skipped: number; flaky: number; startTime: string } })
  : undefined;
const specs = pw ? pw.suites.flatMap(flatten) : [];
const unitPath = resolve(ROOT, 'test-results/unit.json');
const unit = existsSync(unitPath) ? (JSON.parse(readFileSync(unitPath, 'utf8')) as { numPassedTests: number; numFailedTests: number; numTotalTests: number }) : undefined;
const status = (title: string) => {
  const s = specs.find((x) => x.title === title);
  return s ? (s.ok ? 'PASS' : 'FAIL') : 'not run';
};

